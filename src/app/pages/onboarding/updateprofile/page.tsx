import { auth } from "@/src/auth";
import { redirect } from "next/navigation";
import MainContent from './MainContent';


/////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////


export const metadata = {
  title: "Update Profile | Geo Radius News",
  description: "Update your profile details to personalize your local news experience.",
};

/////////////////////////////////////////////////////////////////////////////////////////////////////

export default async function page() {

  const session = await auth();
  if (!session?.user) redirect("/pages/auth/signin");

  /////////////////////////////////////////////////////////////////////////////////////////////////////

  if (session.user.username === false) {
    redirect("/pages/onboarding/createprofile");
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////////

  return (
    <>
      <MainContent />
    </>
  );
}