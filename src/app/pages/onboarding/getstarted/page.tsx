import { cookies } from "next/headers";
import { redirect } from "next/navigation";
import MainContent from "./MainContent";


/////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////

export const metadata = {
  title: "Get Started | Geo Radius News",
  description: "Begin your journey with Geo Radius News. Set up your preferences and location to see relevant updates.",
};

/////////////////////////////////////////////////////////////////////////////////////////////////////

export default async function page() {
  const cookieStore = await cookies();
  const onboarding = cookieStore.get("onboarding")?.value;
  // const NPS = cookieStore.get("NPS")?.value;
  const LPS = cookieStore.get("LPS")?.value;

  /////////////////////////////////////////////////////////////////////////////////////////////////////

  if (onboarding) {
    if (!LPS) redirect("/pages/onboarding/permissions/location");
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////////

  return <MainContent />;
}
